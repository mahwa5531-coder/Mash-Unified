// ----------------------------------------------------------------------
// Helper to extract and format Artifact cards (Documentation, Spreadsheets, Visual Charts)
// ----------------------------------------------------------------------
export function extractArtifacts(msg: Message): ArtifactItem[] {
  const artifacts: ArtifactItem[] = [];
  const seenPaths = new Set<string>();

  const classifyArtifact = (p: string, meta?: any): { isArtifact: boolean; type: 'plan' | 'walkthrough' | 'spreadsheet' | 'chart' | 'doc' } => {
    // DeepSeek Harness domain scoping: positive deliverable classification
    if (!isArtifactPath(p, meta)) {
      return { isArtifact: false, type: 'doc' };
    }
    const lower = p.toLowerCase().replace(/\\/g, '/');
    if (lower.includes('implementation_plan') || lower.includes('plan.md')) {
      return { isArtifact: true, type: 'plan' };
    }
    if (lower.includes('walkthrough')) {
      return { isArtifact: true, type: 'walkthrough' };
    }
    if (/\.(xlsx?|csv|xlsm)$/i.test(lower)) {
      return { isArtifact: true, type: 'spreadsheet' };
    }
    if (/\.(png|jpe?g|svg|webp)$/i.test(lower)) {
      return { isArtifact: true, type: 'chart' };
    }
    return { isArtifact: true, type: 'doc' };
  };

  // 1. Check tools for created artifacts (plans, walkthroughs, spreadsheets, visual charts)
  if (msg.tools && msg.tools.length > 0) {
    for (const t of msg.tools) {
      // Guard against phantom cards: never create deliverable cards for unexecuted, pending, or failed tools
      if (t.status === 'failed' || t.status === 'pending_approval' || (t.status as string) === 'running' || !t.output) continue;
      const out = String(t.output).trim().toLowerCase();
      if (
        out.startsWith('error:') ||
        out.startsWith('validationerror:') ||
        out.startsWith('exception:') ||
        out.startsWith('failed:') ||
        out.includes('validation error') ||
        out.includes('schema validation failed') ||
        out.includes('failed to write') ||
        out.includes('permission denied')
      ) {
        continue;
      }

      let args = t.args || {};
      if (typeof args === 'string') {
        try { args = JSON.parse(args); } catch { args = {}; }
      }
      let rawPath = args.TargetFile || args.AbsolutePath || args.file_path || args.path || args.target_file || args.filepath || args.ImageName;

      // DeepSeek Harness Command Output Grounding: Detect files generated by run_command / shell scripts
      const toolName = (t.name || '').toLowerCase();
      if (!rawPath && (toolName.includes('command') || toolName.includes('shell') || toolName === 'run_code')) {
        const cmdText = `${args.CommandLine || args.cmd || args.command || ''} ${String(t.output || '')}`;
        const match = cmdText.match(/(?:Audit_Deliverables|working_papers|workpapers)[/\\][^\s"'<>|;]+\.(?:md|xlsx?|csv|pdf|png|jpe?g|svg)/i);
        if (match) {
          rawPath = match[0];
        }
      }

      if (rawPath) {
        const pathStr = String(rawPath);
        const meta = args.ArtifactMetadata || args.artifact_metadata;
        const { isArtifact, type } = classifyArtifact(pathStr, meta);
        const canonicalKey = (pathStr.split(/[/\\]/).pop() || pathStr).toLowerCase();
        if (isArtifact && !seenPaths.has(canonicalKey)) {
          seenPaths.add(canonicalKey);
          const rawFilename = pathStr.split(/[/\\]/).pop() || '';
          const rawTitle = rawFilename.replace(/\.[^/.]+$/, '') || 'Artifact';
          const friendlyTitle = rawTitle.replace(/[_-]+/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());

          // Dynamic summaries derived from file type and context (zero hardcoded static boilerplate)
          let dynamicSummary = meta?.Summary || meta?.summary;
          if (!dynamicSummary) {
            if (type === 'plan') {
              dynamicSummary = `Implementation plan for review and execution verification`;
            } else if (type === 'walkthrough') {
              dynamicSummary = `Walkthrough documentation and execution results`;
            } else if (type === 'spreadsheet') {
              dynamicSummary = `${friendlyTitle} audit schedule and testing reconciliation`;
            } else if (type === 'chart') {
              dynamicSummary = `${friendlyTitle} visual analytical exhibit`;
            } else {
              dynamicSummary = `${friendlyTitle} documentation and analysis findings`;
            }
          }

          const isFeedbackRequested = Boolean(meta?.RequestFeedback ?? meta?.requestFeedback ?? meta?.request_feedback);

          artifacts.push({
            id: pathStr,
            title: friendlyTitle,
            summary: dynamicSummary,
            filePath: pathStr,
            type,
            requestFeedback: isFeedbackRequested,
          });
        }
      }
    }
  }

  // Strict Turn Isolation: Grounded solely in actions executed in this exact turn.
  // Prose links never resurrect deliverables from past turns.
  return artifacts;
}
